/// เวลาในชั้นกรองนี้เป็น **จำนวนเต็มมิลลิวินาทีนับจาก epoch (UTC)** เสมอ
///
/// ไม่ใช่ `DateTime` ไม่ใช่ `Duration` — เหตุผลคือตรรกะนี้ต้องถูกเขียนซ้ำเป็น
/// Kotlin และ Swift แล้วให้ผลตรงกันทุกช่อง:
///
/// - **`Date` ของ Swift เก็บเป็น `Double` วินาที** ค่ามิลลิวินาทีจำนวนมากแทนไม่ได้
///   เป๊ะ การเทียบเวลาจะกลายเป็นการเทียบทศนิยม
/// - `TimeInterval` ของ Swift กับ `Duration` ของ Kotlin/Java คนละความละเอียดกัน
/// - **จำนวนเต็มมิลลิวินาทีเป็นชนิดเดียวที่ทั้งสามภาษาแทนได้ตรงกันทุกค่า**
///   (`int` บน Dart VM · `Long` บน Kotlin · `Int64` บน Swift)
///
/// epoch มิลลิวินาทีตอนนี้อยู่ราว 1.79 × 10¹² เล็กกว่า 2⁵³ มาก จึงไม่ล้มแม้ผ่าน
/// `Double` ของ JSON
///
/// ชนิดวันเวลาของแพลตฟอร์มถูกจำกัดไว้ที่ **ขอบเท่านั้น** — ในแพ็กเกจนี้คือ
/// `region_log.dart` ซึ่งอ่าน/เขียนไฟล์หลักฐาน
typedef EpochMillis = int;

/// แปลงเป็นข้อความอ่านออกสำหรับ **ข้อความ debug เท่านั้น**
///
/// ⚠️ ไม่ใช่ส่วนหนึ่งของสัญญา และไม่มีอะไรเทียบค่านี้ — port ไม่ต้องทำให้เหมือน
String debugTime(EpochMillis millis) =>
    DateTime.fromMillisecondsSinceEpoch(millis, isUtc: true).toIso8601String();
