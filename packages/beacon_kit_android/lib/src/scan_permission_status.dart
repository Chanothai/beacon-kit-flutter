/// ผลของการขอสิทธิ์สแกน BLE บน Android
///
/// **ทำไมต้องมี `permanentlyDenied` แยกจาก `denied`** — บทเรียนตรงจากบั๊กบน iOS
/// (ARCHITECTURE.md ADR-6 / เช็คลิสต์ข้อ 1 บั๊กรอบ 2): ถ้าแยกไม่ออกว่า "ผู้ใช้เพิ่ง
/// ปฏิเสธครั้งนี้" กับ "ระบบจะไม่ถาม prompt ให้อีกแล้ว" โค้ดจะไปรอ callback ที่ไม่มี
/// วันมา แล้วหน้าจอเงียบสนิทโดยไม่มี error — เป็นอาการที่ดีบักยากที่สุด
enum ScanPermissionStatus {
  /// ได้สิทธิ์ครบทุกตัวที่ต้องใช้ เริ่มสแกนได้
  granted,

  /// ผู้ใช้ปฏิเสธในรอบนี้ แต่ระบบยังยอมแสดง prompt ให้อีกได้ — ขอใหม่ได้
  denied,

  /// ระบบจะไม่แสดง prompt ให้อีกแล้ว (ผู้ใช้เลือก "Don't ask again" หรือถูก
  /// นโยบายของเครื่องบล็อก) — **ห้ามเรียกขอสิทธิ์ซ้ำ** เพราะจะได้ผลลัพธ์เดิมทันที
  /// โดยผู้ใช้ไม่เห็นอะไรเลย ทางเดียวคือพาผู้ใช้ไปหน้า Settings ของแอป
  permanentlyDenied,

  /// ยังไม่เคยถาม
  notDetermined,
}
